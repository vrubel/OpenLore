const STRING_TABLES: Record<Locale, Record<StringKey, string>> = { en: STRINGS_EN, ru: STRINGS_RU };

/**
 * Look up a hardcoded Markdown string for the current locale, optionally filling
 * `{name}` placeholders from `vars`. The English table holds the verbatim original
 * literals, so `t()` under the default `en` locale reproduces today's output exactly.
 */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRING_TABLES[currentLocale][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}
